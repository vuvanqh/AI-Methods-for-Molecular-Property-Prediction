from pydantic import BaseModel, Field


class SimilarCompoundModel(BaseModel):  # TODO add more fields?
    smiles: str = Field(
        ...,
        description="The similar compound in SMILES format.",
        examples=["O=C(C)Oc1ccccc1C(=O)O"],
    )
    similarity_score: float = Field(
        ...,
        description="Similarity score between the original and similar compound.",
        examples=[0.87],
    )
    sources: list[str]  # TODO which required and add field with description


class GNNXAIInferenceResponse(BaseModel):
    predictions: dict[str, bool]
    probabilities: dict[str, float]
    atomscores: dict[str, dict[int, float | None]] = Field(
        ...,
        description="Atom-level scores for each atom in the molecule, where the key of the outer dict is the property, key of the inne dict is the atom index and the value is a dictionary of scores for each property.",
    )
    molblock: str = Field(
        description="MolBlock representation of the molecule for visualization purposes."
    )


class MoleculeModel(BaseModel):
    smiles: str = Field(
        ...,
        description="Canonical SMILES generated by RDKit.",
        examples=["CC(=O)Oc1ccccc1C(=O)O"],
    )
    formula: str = Field(..., description="Molecular formula.", examples=["C9H8O4"])
    molar_mass: float = Field(
        ..., description="Average molar mass in g/mol.", examples=[180.16]
    )
    atom_count: int = Field(
        ..., description="Number of atoms, including hydrogens.", examples=[21]
    )
    bond_count: int = Field(
        ..., description="Number of bonds, including bonds to hydrogens.", examples=[21]
    )


class PredictionResponse(BaseModel):
    molecule: MoleculeModel = Field(
        ..., description="Structural descriptors of the queried molecule"
    )
    properties_xai_data: GNNXAIInferenceResponse = Field(
        ..., description="GNN-XAI inference results"
    )

    similar_compounds: list[SimilarCompoundModel] = Field(
        ..., description="Top-K nearest analogues found using RAG."
    )
    llm_summary: str = Field(..., description="Summary generated by LLM")


class InferenceRequest(BaseModel):
    smiles: str = Field(..., description="SMILES string sent by orchestrator")


class ErrorResponse(BaseModel):
    message: str = Field(..., description="Error message.")

