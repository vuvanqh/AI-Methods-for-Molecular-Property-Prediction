from pydantic import BaseModel, Field
from typing import List, Dict, Any


class SimilarCompoundModel(BaseModel): #TODO add more fields?
    smiles: str = Field(
        ..., 
        description="The similar compound in SMILES format.", 
        example="O=C(C)Oc1ccccc1C(=O)O"
    )
    similarity_score: float = Field(
        ..., 
        description="Similarity score between the original and similar compound.",
        example=0.87
    )
    sources: List[str]  #TODO which required and add field with description




class GNNXAIInferenceResponse(BaseModel):
    mappedsmiles: str = Field(
        ...,
    )
    predictions: Dict[str, bool]
    atomscores: Dict[str, List[float]]


class PredictionResponse(BaseModel):
    properties_xai_data: GNNXAIInferenceResponse = Field(
        ...,
        description="GNN-XAI inference results"
    )
    
    similar_compounds: List[SimilarCompoundModel] = Field(
        ..., 
        description="Top-K nearest analogues found using RAG."
    )
    llm_summary: str  = Field(
        ..., 
        description="Summary generated by LLM"
    ) 

class ErrorResponse(BaseModel):
    message: str = Field(..., description="Error message.")

