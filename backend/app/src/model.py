from pydantic import BaseModel, Field
from typing import List, Dict, Any

class PredictionRequest(BaseModel):
    smiles: str = Field(
        ..., 
        description="The molecule in SMILES format.", 
        example="O=C(C)Oc1ccccc1C(=O)O"
    )

class PredictionResponse(BaseModel):
    smiles: str = Field(
        ..., 
        description="The molecule in SMILES format.", 
        example="O=C(C)Oc1ccccc1C(=O)O"
    )
    predictions: Dict[str, Any] = Field(
        ..., 
        description="Multitask-GNN properties predictions"
    )
    xai_attributions: Dict[str, List[Any]] = Field(
        ...,
        description="XAI attributions"
    )
    #TODO add what else is needed for XAI
    similar_compounds: List #TODO
    llm_summary: str  = Field(
        ..., 
        description="Summary generated by LLM"
    ) #TODO


class GNNXAIInferenceResponse(BaseModel):
    smiles: str
    predictions: Dict[str, Any]
    xai_attributions: Dict[str, List[Any]]

class ErrorResponse(BaseModel):
    message: str = Field(..., description="Error message.")

